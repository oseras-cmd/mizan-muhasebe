/** Yıl+ay için Yİ-ÜFE değeri; yoksa null döner. yil: 1994-2026, ay: 1-12. */
export function yiufeDeger(yil: number, ay: number): number | null {
  if (!Number.isInteger(yil) || !Number.isInteger(ay) || yil < YIUFE_BASLANGIC_YILI || ay < 1 || ay > 12) return null;
  const idx = (yil - YIUFE_BASLANGIC_YILI) * 12 + (ay - 1);
  const v = YIUFE[idx];
  return typeof v === "number" ? v : null;
}

/** Belirli bir yıla ait yayımlanmış son ay (ör. 2026 → 8); yayım yoksa 0. */
export function yiufeSonAy(yil: number): number {
  const guncel = yiufeGuncelDonem();
  if (yil > guncel.yil) return 0;
  if (yil < guncel.yil) return 12;
  return guncel.ay;
}
export function yiufeGuncelDonem(): { yil: number; ay: number } {
  const maxIdx = YIUFE.length - 1;
  const mutlak = YIUFE_BASLANGIC_YILI * 12 + maxIdx; // örn 1994*12+391
  const yil = Math.floor(mutlak / 12);
  const ay = (mutlak % 12) + 1;
  return { yil, ay };
}
